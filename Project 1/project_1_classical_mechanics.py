import math
from scipy.integrate import quad
import matplotlib.pyplot as plt

# a.) plot PE with k = 1 = A
PE = lambda x: (x**4)
c = -1
E_values = []
x_values = []
while c <= 1:
    E = PE(c)
    E_values.append(E)
    x_values.append(c)
    c += 1e-2
plt.ylabel("Potential Energy (Joules)")
plt.xlabel("Position (meters)")
plt.plot(x_values, E_values)
plt.show()

"""As to be expected, as position approaches the amplitude the potential energy increases and forces the mass back to equilibrium (x=0).

b.) The time for the mass to reach maximum displacement is given by equation 4.58 from the textbook.

Using T(Kinetic Energy) = $\frac{1}{2}$m$v^2$ = E(Total Energy) - U(Potential Energy) = $k*(A^4 -x^4)$, solve for v and substitute into  4.58.

\begin{align}
        \text{from 4.58: t = } & \sqrt{\frac{m}{2k}} \int_0^{A} \frac{dx}{\sqrt{A^4 - x^4}}
\end{align}

c.) the period for the oscillation of the mass-spring system is just 4 times this integral and can be simplified by substituting u = $\frac{x}{A}$

\begin{align}
        \text{from 4.58: τ = } \frac{1}{A} \sqrt{\frac{8m}{k}} \int_0^{1} \frac{du}{\sqrt{1-u^4}}
\end{align}

d.) for the final part, the two integrals we found need to be evaluated numerically using computer software. in the case that m=k=A=1 our first integral is simplified to:

\begin{align}
        \sqrt{\frac{1}{2}} \int_0^{1} \frac{dx}{\sqrt{1 - x^4}}
\end{align}

and our second integral becomes:

\begin{align}
        \sqrt{8} \int_0^{1} \frac{du}{\sqrt{1 - u^4}}
\end{align}
"""

# time for the mass to reach the amplitude
t = lambda x: (.5**.5)/math.sqrt(1-x**4)
time = quad(t, 0, 1)[0]
print("Time for mass to reach amplitude:", time)

# period of oscillation
t = lambda u: (8**.5)/math.sqrt(1-u**4)
time = quad(t, 0, 1)[0]
print("\n"+ "Period of oscillation:", time)

"""This is the numerical solution for a the quartic oscillator with potential U(x) = $kx^4$. A very simple example of a quartic oscillator is a bead moving along a frictionless rod while attached to two springs on opposite sides of the bead. Some key differences between a normal Hooke's law oscillator and a quartic oscillator are in the restoring force and the trajectory. The trajectory of a Hooke's law oscillator is a very simple sinusoidal curve, whereas the trajectory of a quartic oscillator can be much more complex, having multiple points of equilibrium and the curve can take on many different shapes. this example has 2 stable equilibrium points and one unstable equillibrium point.

The numerical solution is the most accurate solution for the period of oscillation, but in a pinch, there are a few ways to find an approximate solution.

1. Small amplitude approximation: at very small oscillations the quartic potential and harmonic potential are very close. therefore, to apply this approximation, use the equation for the hooke's law period of oscillation $τ = 2π\sqrt{\frac{m}{k}}$ which in this case would just be $2π$. obviously, this is a poor approximation in this case, so we will move on to the next.
2. Maclaurin series expansion: The maclaurin series is a special case of the Taylor series that uses the derivates of a function to find its approximate value at a point. In the case of the Maclaurin series, that point is X = 0. I have included a plot of both the original integrand and the maclaurin series approximation in the next code block, and my work for the maclaurin series in the next text block.

The Maclaurin series is defined as follows:

\begin{align}
    f(x) ≈ \sum_{n=0}^{\infty}\frac{f^n(0)}{n!}x^n
\end{align}

for our problem, the maclaurin series yields

\begin{align}
    f(x) = \frac{1}{\sqrt{1-x^4}} ≈ \sum_{n=0}^{\infty}\frac{f^n(0)}{n!}x^n = 1 + \frac{x^4}{2} + \frac{3x^8}{8} + \frac{5x^{12}}{16} + \frac{35x^{16}}{128} + \frac{63x^{20}}{256} + \frac{231x^{24}}{1024}
\end{align}

and finally, integrate the approximation of the function with our original boundaries to find the approximate value.

\begin{align}
    ∫_0^1 f(x) ≈ 1.1525318745286575
\end{align}

Error: 12%

to find the values we are looking for, just simply plug the coefficients for each back in.

1. Time for mass to reach amplitude = $\sqrt{1/2}$ * 1.1525 =  0.81496 (12% error)

2. Period of oscillation = $\sqrt{8}$ * 1.1525 = 3.2598 (12% error)

because of the relatively small error, I would say this is a great way to approximate the integral if you do not have access to a computer, and it only gets more accurate as the series expands.
"""

# show graph of integrand and approximation

PE = lambda x: 1/math.sqrt(1-x**4)
c=-.99
